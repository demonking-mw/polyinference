"""Replaceable runtime boundary. No providers, SQLite or scheduler imports."""

from __future__ import annotations

from collections.abc import Awaitable, Callable, Sequence
from typing import Any, Protocol

from .contracts import ArtifactRef, OperationRequest, OperationResult, ProcessSpec, Scope


class WriteScopeError(ValueError):
    def __init__(self, workspace_id, phase, paths, allowed):
        self.detail = {"code": "write_scope_exceeded", "workspace_id": workspace_id,
                       "phase": phase, "paths": sorted(paths), "allowed_write_paths": sorted(allowed)}
        super().__init__(f"Private changes exceed write scope ({phase}): " + ", ".join(sorted(paths)))


class RecordConflict(RuntimeError):
    """A compare-and-publish precondition changed; no partial update was applied."""


class RecordPorts(Protocol):
    def get(self, key: str) -> tuple[int, dict] | None: ...
    def scan(self, prefix: str) -> list[tuple[str, int, dict]]: ...
    def put_once(self, key: str, body: dict) -> None: ...
    def compare_and_publish(
        self, expected: dict[str, int], updates: dict[str, dict], immutable: dict[str, dict] | None = None
    ) -> None: ...


class ArtifactPorts(Protocol):
    def put(self, data: bytes, scope: Scope, media_type: str = "application/json") -> ArtifactRef: ...
    def read(self, ref: ArtifactRef) -> bytes: ...


class OperationPorts(Protocol):
    async def execute(self, request: OperationRequest) -> OperationResult: ...
    def uncertain(self, *, include_isolated: bool = False) -> list[str]: ...
    async def prepare_resume(self, request_ref: str) -> None: ...
    def recovery_allowed(self, failed_id: str, scope: Scope, *, operation_id: str | None = None) -> str: ...
    async def recover_model(self, failed_id: str, request: OperationRequest, reason: str) -> OperationResult: ...
    def settlement(self, process_id: str) -> dict: ...
    def park_process(self, process_id: str) -> dict: ...
    def bind_recovery(self, process_id: str, predecessor: str, *, require_park: bool = True) -> None: ...
    def process_deadline(self, process_id: str) -> Any: ...
    async def progress(self, process_id: str) -> dict: ...
    def resource_state(self, process_id: str) -> dict: ...
    def register_progress_source(self, name: str, source: Any) -> None: ...

    # Optional negotiated runtime/inference-retry extension. Agents need not
    # implement repair: no offered replacement means a bounded original retry.
    def register_response_validator(self, schema_ref: str, validator: Any) -> None: ...
    def register_response_schema(self, schema_ref: str, schema: dict) -> None: ...
    def inference_calls_used(self, process_id: str) -> int: ...
    async def offer_retry(self, operation_id: str, replacement: Any, *, process_id: str) -> None: ...


class ExclusivePorts(Protocol):
    async def acquire(self, resource_key: str, process_id: str) -> str: ...
    async def release(self, permit_ref: str, process_id: str) -> None: ...
    def owns(self, permit_ref: str, resource_key: str, process_id: str) -> bool: ...


class CapabilityPorts(Protocol):
    schema_digest: str
    effect_class: str
    workspace: bool


class CapabilityRegistryPorts(Protocol):
    def get(self, name: str) -> CapabilityPorts: ...


class ProcessPorts(Protocol):
    on_cancel: Callable[[str], None] | None

    def register(self, spec: ProcessSpec, binding_ref: str, *, management: bool = False,
                 capabilities: Sequence[str] = ()) -> None: ...
    def start(self, process_id: str, factory: Callable[[], Awaitable[Any]]) -> Any: ...
    def finish(self, process_id: str, *, state: str = "completed",
               output_refs: Sequence[ArtifactRef] = ()) -> None: ...
    def status(self, process_id: str) -> dict: ...
    def cancel(self, process_id: str, reason: str = "operator cancellation") -> None: ...
    async def wait(self, process_id: str, timeout: float | None = None) -> dict: ...


class ToolPorts(Protocol):
    def register_check(self, check: Any) -> Any: ...


class OutputPorts(Protocol):
    def prepare(self, destination: str, baseline: dict) -> Any: ...


class WorkspacePorts(Protocol):
    async def attach(self, manifest: Any, path: Any, *, authorized_root: Any, **options) -> Any: ...
    def is_attached(self, workspace_id: str) -> bool: ...
    async def initialize(self) -> Any: ...
    async def tree(self, commit_id: str, process_id: str = "runtime") -> dict: ...
    async def prepare_snapshot(self, code: Any, snapshot_id: str, *, binding_ref: str | None = None) -> str: ...
    async def prepare_artifact_snapshot(self, snapshot_id: str, files: dict[str, Any]) -> str: ...
    async def prepare_workspace_snapshot(self, workspace_id: str, snapshot_id: str) -> str: ...
    async def private_tree(self, workspace_id: str) -> dict: ...
    def snapshot_root(self, snapshot_id: str) -> Any: ...
    async def create(
        self,
        workspace_id: str,
        process_id: str,
        task_ref: str,
        base: Any,
        write_paths: list[str],
        read_paths: list[str],
        *, capabilities: list[str] | None = None, check_names: list[str] | None = None,
        expandable: bool = False,
    ) -> Any: ...
    def configure_grant(self, workspace_id: str, **options) -> Any: ...
    def authority(self, workspace_id: str) -> dict: ...
    def current(self, workspace_id: str) -> Any: ...
    async def revision(self, workspace_id: str) -> Any: ...
    async def retag_task_spec(
        self, workspace_id: str, spec_id: str, updates: dict, immutable: dict
    ) -> None: ...
    async def select_branch(self, workspace_id: str, name: str, create: bool = False) -> dict: ...
    async def preserve_delta(self, workspace_id: str) -> str: ...
    async def validate_handoff(self, delta_ref: str, base: Any, write_paths: list[str]) -> Any: ...
    async def apply_handoff(self, workspace_id: str, delta_ref: str) -> None: ...
    async def integrate(self, workspace_id: str, head: Any, permit_ref: str) -> Any: ...
    async def abort(self, workspace_id: str) -> None: ...
    async def commit(self, workspace_id: str, head: Any, operation_id: str) -> Any: ...


class RuntimePorts(Protocol):
    records: RecordPorts
    artifacts: ArtifactPorts
    operations: OperationPorts
    exclusive: ExclusivePorts
    workspaces: WorkspacePorts
    capabilities: CapabilityRegistryPorts
    processes: ProcessPorts
    tools: ToolPorts
    outputs: OutputPorts
    checkpointer: Any
    on_reconciled: Callable[[OperationRequest, OperationResult], Awaitable[None]] | None

    def negotiate(self, requirements: list) -> None: ...
    def install_workspaces(self, provider: WorkspacePorts) -> None: ...
    def publish_records(self, arguments: dict, process_id: str) -> Any: ...
    def register_agent_protocol(
        self, name: str, schema: dict, *, workspace: str = "snapshot", brokered: bool = False,
        instructions: str = "",
    ) -> None: ...
    def register_capability(self, name: str, handler: Any, **options) -> CapabilityPorts: ...
    def register_publication_policy(self, program_id: str, policy: Any) -> None: ...
    async def close(self) -> None: ...
