"""Replaceable runtime boundary. No providers, SQLite or scheduler imports."""

from __future__ import annotations

from typing import Any, Protocol

from .contracts import ArtifactRef, OperationRequest, OperationResult, Scope


class RecordPorts(Protocol):
    def get(self, key: str) -> tuple[int, dict] | None: ...
    def scan(self, prefix: str) -> list[tuple[str, int, dict]]: ...
    def compare_and_publish(
        self, expected: dict[str, int], updates: dict[str, dict], immutable: dict[str, dict] | None = None
    ) -> None: ...


class ArtifactPorts(Protocol):
    def put(self, data: bytes, scope: Scope, media_type: str = "application/json") -> ArtifactRef: ...
    def read(self, ref: ArtifactRef) -> bytes: ...


class OperationPorts(Protocol):
    async def execute(self, request: OperationRequest) -> OperationResult: ...
    def uncertain(self) -> list[str]: ...
    def settlement(self, process_id: str) -> dict: ...
    def park_process(self, process_id: str) -> dict: ...
    def bind_recovery(self, process_id: str, predecessor: str, *, require_park: bool = True) -> None: ...
    def process_deadline(self, process_id: str) -> Any: ...
    async def progress(self, process_id: str) -> dict: ...
    def resource_state(self, process_id: str) -> dict: ...
    def register_progress_source(self, name: str, source: Any) -> None: ...

    # Optional negotiated runtime/inference-retry extension. Agents need not
    # implement repair: no offered replacement means a bounded original retry.
    def register_response_validator(self, schema_ref: str, validator: Any) -> None: ...
    def register_response_schema(self, schema_ref: str, schema: dict) -> None: ...
    def inference_calls_used(self, process_id: str) -> int: ...
    async def offer_retry(self, operation_id: str, replacement: Any, *, process_id: str) -> None: ...


class ExclusivePorts(Protocol):
    async def acquire(self, resource_key: str, process_id: str) -> str: ...
    async def release(self, permit_ref: str, process_id: str) -> None: ...
    def owns(self, permit_ref: str, resource_key: str, process_id: str) -> bool: ...


class WorkspacePorts(Protocol):
    async def initialize(self) -> Any: ...
    async def tree(self, commit_id: str, process_id: str = "runtime") -> dict: ...
    async def prepare_snapshot(self, code: Any, snapshot_id: str) -> str: ...
    async def prepare_workspace_snapshot(self, workspace_id: str, snapshot_id: str) -> str: ...
    async def private_tree(self, workspace_id: str) -> dict: ...
    def snapshot_root(self, snapshot_id: str) -> Any: ...
    async def create(
        self,
        workspace_id: str,
        process_id: str,
        task_ref: str,
        base: Any,
        write_paths: list[str],
        read_paths: list[str],
    ) -> Any: ...
    def current(self, workspace_id: str) -> Any: ...
    async def revision(self, workspace_id: str) -> Any: ...
    def retag_task_spec(self, workspace_id: str, spec_id: str, updates: dict, immutable: dict) -> None: ...
    async def select_branch(self, workspace_id: str, name: str, create: bool = False) -> dict: ...
    async def preserve_delta(self, workspace_id: str) -> str: ...
    async def validate_handoff(self, delta_ref: str, base: Any, write_paths: list[str]) -> Any: ...
    async def apply_handoff(self, workspace_id: str, delta_ref: str) -> None: ...
    async def integrate(self, workspace_id: str, head: Any, permit_ref: str) -> Any: ...
    async def abort(self, workspace_id: str) -> None: ...
    async def commit(self, workspace_id: str, head: Any, operation_id: str) -> Any: ...


class RuntimePorts(Protocol):
    records: RecordPorts
    artifacts: ArtifactPorts
    operations: OperationPorts
    exclusive: ExclusivePorts
    workspaces: WorkspacePorts
    checkpointer: Any

    def negotiate(self, requirements: list) -> None: ...
    async def close(self) -> None: ...
